import { NODE_META, type ScenarioDocument, type ScenarioEdge, type ScenarioNode, type ScenarioPort, type SceneObject } from "@/lib/scenario/types";

function ports(kind: ScenarioNode["kind"]): ScenarioPort[] {
  return NODE_META[kind].defaultPorts.map((p) => ({ ...p }));
}

function loc(
  id: string,
  title: string,
  x: number,
  y: number,
  locationId: string,
  description: string,
  background?: string,
  backgrounds?: { id: string; name: string; url: string; requiresFlag?: string }[],
  sceneObjects?: SceneObject[],
): ScenarioNode {
  return {
    id,
    kind: "location",
    x,
    y,
    ports: ports("location"),
    data: { title, locationId, description, background, backgrounds, sceneObjects },
  };
}

function pin(
  id: string,
  label: string,
  url: string,
  x: number,
  y: number,
  w: number,
  h: number,
  linkNodeId: string,
): SceneObject {
  return {
    id,
    kind: "npc",
    label,
    url,
    x,
    y,
    w,
    h,
    linkNodeId,
    interaction: "talk",
    percent: true,
  };
}

function spark(id: string, label: string, x: number, y: number, linkNodeId: string): SceneObject {
  return {
    id,
    kind: "hotspot",
    label,
    x,
    y,
    w: 10,
    h: 14,
    linkNodeId,
    interaction: "inspect",
    percent: true,
  };
}

function node(
  id: string,
  kind: ScenarioNode["kind"],
  title: string,
  x: number,
  y: number,
  data: Omit<ScenarioNode["data"], "title">,
): ScenarioNode {
  return { id, kind, x, y, ports: ports(kind), data: { ...data, title } };
}

function edge(
  from: string,
  to: string,
  fromPort: string,
  toPort: string,
  label?: string,
  extra?: Partial<ScenarioEdge>,
): ScenarioEdge {
  return { id: `e_${from}_${to}_${fromPort}`, from, to, fromPort, toPort, label, ...extra };
}

